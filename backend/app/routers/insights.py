"""Dashboard, alerts, leakage, forecasting, simulation, reports, advisor."""
from fastapi import APIRouter, Depends, Query
from fastapi.responses import PlainTextResponse
from sqlalchemy.orm import Session
from .. import ai, config
from ..ai import context as ai_context
from ..ai.demo import DemoProvider
from ..auth import Principal, require
from ..db import get_db
from ..schemas import AdvisorRequest, SimulationIn
from ..services import analytics as A, reports
from .deps import Ctx, analysis_ctx

router = APIRouter(prefix="/api", tags=["insights"])


@router.get("/dashboard")
def dashboard(c: Ctx = Depends(analysis_ctx)):
    return A.dashboard(c.snap, c.period)


@router.get("/alerts")
def alerts(c: Ctx = Depends(analysis_ctx)):
    a = A.alerts(c.snap, c.period)
    return {"period": A._period_meta(c.snap, c.period), "count": len(a), "alerts": a}


@router.get("/leakage")
def leakage(c: Ctx = Depends(analysis_ctx)):
    return A.leakage(c.snap, c.period)


@router.get("/forecast")
def forecast(weeks: int = Query(4, ge=1, le=12), location_id: int | None = None, db: Session = Depends(get_db),
             _: Principal = Depends(require("read"))):
    return A.forecast(A.Snapshot(db, location_id), weeks)


@router.post("/simulate")
def simulate(body: SimulationIn, db: Session = Depends(get_db), _: Principal = Depends(require("read"))):
    snap = A.Snapshot(db, body.location_id)
    return A.simulate(snap, body.ingredient_price_changes_pct, body.menu_prices, body.volume_changes_pct, body.basis_weeks)


@router.get("/reports")
def report(c: Ctx = Depends(analysis_ctx), _: Principal = Depends(require("report:read"))):
    return reports.build(c.snap, c.period)


@router.get("/reports/download", response_class=PlainTextResponse)
def report_download(c: Ctx = Depends(analysis_ctx), _: Principal = Depends(require("report:read"))):
    r = reports.build(c.snap, c.period)
    name = f"margin-os-report-{c.period.start}-{c.period.end}.md"
    return PlainTextResponse(reports.to_markdown(r), media_type="text/markdown",
                             headers={"Content-Disposition": f'attachment; filename="{name}"'})


@router.post("/advisor")
def advisor(body: AdvisorRequest, db: Session = Depends(get_db), _: Principal = Depends(require("read"))):
    snap = A.Snapshot(db, body.location_id)
    period = snap.period(body.start, body.end)
    ctx = ai_context.build(snap, period, body.question)
    provider = ai.get_provider()
    notice = None
    try:
        result = provider.answer(body.question, ctx)
        live, name = provider.live, provider.name
    except Exception as e:  # network/auth/rate-limit: fall back honestly
        result = DemoProvider().answer(body.question, ctx)
        live, name = False, "demo"
        notice = f"Live Claude call failed ({type(e).__name__}); showing the rule-based demo advisor instead."
    label = (f"Live Claude API ({config.ANTHROPIC_MODEL})" if live
             else "Demo advisor: rule-based answer from your data, not live AI")
    return {
        "provider": name, "live_ai": live, "model": config.ANTHROPIC_MODEL if live else None, "label": label,
        "notice": notice or (None if live else "DEMO MODE: no ANTHROPIC_API_KEY is configured. This answer is generated by "
                                               "deterministic rules from your restaurant's figures; it is not a live Claude response."),
        "question": body.question, "answer": result["answer"], "intent": result.get("intent"),
        "scenario": ctx["scenario"]["result"] if ctx.get("scenario") else None,
        "period": ctx["period"],
        "mode": "live" if live else "demo",  # v1 alias
    }
