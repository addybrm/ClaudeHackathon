import { Pill, PageHeader, Panel, money } from '../ui';
import { ROLE_LABEL } from '../api';
import { useApp } from '../app-context';

function Row({ label, children }: { label: string; children: React.ReactNode }) {
  return <div className="srow"><span>{label}</span><div>{children}</div></div>;
}

export function SettingsPage() {
  const { core, live, health, user, refresh, loading, openLogin, signOut, locations } = useApp();
  const permissions: [string, boolean][] = [
    ['View analysis', true], ['Edit menu and recipes', ['owner', 'manager'].includes(user.role)], ['Upload and confirm invoices', ['owner', 'manager', 'finance'].includes(user.role)],
    ['Record waste', ['owner', 'manager', 'kitchen'].includes(user.role)], ['View and download reports', ['owner', 'manager', 'finance'].includes(user.role)],
  ];
  return (
    <>
      <PageHeader eyebrow="Workspace" title="Settings" subtitle="Connection, account and how your data and AI are used." />
      <div className="grid g-even">
        <Panel title="Data connection" actions={<button className="btn sm" onClick={refresh} disabled={loading}>{loading ? 'Checking…' : 'Check connection'}</button>}>
          <Row label="Status">{live ? <Pill tone="pos" dot>Connected to the API</Pill> : <Pill tone="warn" dot>Offline sample data</Pill>}</Row>
          <Row label="Data">{live ? (core.restaurant.isDemo ? 'Fictional demonstration restaurant. Not real business data.' : 'Your restaurant records') : 'Fixed offline illustration'}</Row>
          <Row label="Locations">{live ? (locations.length ? locations.map(l => `${l.name}, ${l.city}`).join(' · ') : '—') : '—'}</Row>
          <Row label="Food-cost target">{core.kpis.target_food_cost_pct}% of selling price</Row>
          <Row label="Currency">{core.restaurant.currency} ({money(1234.5, core.restaurant.currency, 2)})</Row>
          {!live && <p className="muted small">To use live data set <code>VITE_USE_API=true</code> and <code>VITE_API_BASE_URL</code> in <code>.env</code>, and start the backend.</p>}
        </Panel>

        <Panel title="AI advisor">
          <Row label="Provider">{health.advisorLive ? <Pill tone="brand" dot>Live Claude</Pill> : <Pill tone="warn" dot>{live ? 'Demo advisor (rule-based)' : 'Offline sample'}</Pill>}</Row>
          <p className="muted small">{health.advisorLive ? 'Answers are generated by Claude from your verified figures. The API key is held by the server and never sent to the browser.' : 'No Anthropic API key is configured on the server, so answers come from a deterministic demo advisor that uses your real figures. It is not a language model, and every answer says so.'}</p>
        </Panel>

        <Panel title="Account">
          <Row label="Signed in as">{user.name}</Row>
          <Row label="Email">{user.email}</Row>
          <Row label="Role"><Pill tone="brand">{ROLE_LABEL[user.role]}</Pill></Row>
          {user.demo && <p className="muted small">{live ? 'This is a demo session: this server does not require sign-in, so you act as the demo owner.' : 'Offline sample session.'}</p>}
          {live && <div className="row gap pad-t"><button className="btn sm" onClick={openLogin}>{user.demo ? 'Sign in' : 'Switch account'}</button>{!user.demo && <button className="btn sm" onClick={signOut}>Sign out</button>}</div>}
        </Panel>

        <Panel title="What your role can do">
          <ul className="perms">{permissions.map(([l, ok]) => <li key={l} className={ok ? 'yes' : 'no'}><span aria-hidden>{ok ? '✓' : '–'}</span>{l}{!ok && <small> (not for your role)</small>}</li>)}</ul>
        </Panel>

        <Panel title="Data and privacy" className="span-all">
          <p className="muted small">This build runs on fictional demonstration data only. Before real restaurant data is used it needs HTTPS, required sign-in, a data-processing agreement with its AI and hosting providers, a privacy notice and a retention policy to meet UK data-protection requirements. See <code>docs/ARCHITECTURE.md</code>.</p>
        </Panel>
      </div>
    </>
  );
}
